    func testElementsInsideAForEachAreProbedAndTheClosureSurvives() {
        // `ForEach` is the most common list shape in SwiftUI, and it is an edge
        // shape for a syntactic reason: its trailing closure carries a SIGNATURE
        // (`row in`), and the first statement's leading trivia is the only thing
        // separating `in` from that statement. The walk rebuilds each statement
        // from a `.trimmed` expression, so a probe attached here glued the two
        // together — `{ row inText(row.title) }`, which is not Swift at all.
        //
        // The defect is invisible to every test that uses a signature-less
        // closure, which is every other snapshot in this file, so the shape has
        // to be pinned explicitly rather than assumed to follow from the others.
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    ForEach(rows) { row in
                        Text(row.title)
                    }
                }
            }
            """,
            expandedSource: """
            struct Row: View {
                var body: some View {
                    ForEach(rows) { row in
                        Text(row.title)
                    }
                }

