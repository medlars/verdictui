    func testAMultiStatementBodyIsReportedRatherThanSilentlyLeftUnprobed() {
        // The walk rewrites a single expression. A body it cannot rewrite must
        // SAY so: generating an unprobed passthrough would compile, render, and
        // produce a tree with a root and nothing under it, so every rule would
        // report PASS on a screen nobody instrumented. A false green is this
        // product's worst failure mode.
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    let label = "hi"
                    return Text(label)
                }
            }
            """,
