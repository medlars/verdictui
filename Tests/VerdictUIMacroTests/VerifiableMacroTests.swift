    func testElementsInsideAConditionalBranchAreProbed() {
        // A `@ViewBuilder` conditional is a STATEMENT, not an expression, and the
        // walk rewrites only statements that ARE expressions. So every element in
        // every branch went unprobed — the same false-green shape as the explicit
        // -probe swallow: the surrounding container's probed siblings make the
        // tree look observed, and every rule then reports PASS about branch
        // content nobody instrumented.
        //
        // Both branches are probed, and the id counter runs across them rather
        // than resetting per branch: only one branch renders, so two elements
        // sharing `Row.text.0` would be invisible at runtime and would collide
