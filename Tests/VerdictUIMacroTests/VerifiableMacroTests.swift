@testable import VerdictUIMacros

/// Expansion tests for `@Verifiable`.
///
/// `assertMacroExpansion` compares generated *source text*, which makes these
/// tests precise and also makes them the weaker half of the wave's evidence: a
/// macro can emit perfectly well-formed source that names a type which does not
/// exist, and a text comparison cannot tell. `VerifiableCompilationTests` is the
/// other half — it imports the macro for real and renders the result, so the
/// compiler is the oracle. Neither half alone is sufficient.
final class VerifiableMacroTests: XCTestCase {
    private let macros: [String: any Macro.Type] = ["Verifiable": VerifiableMacro.self]

    // MARK: - The happy path

    func testAttachingToAViewStructGeneratesTheProbedBody() {
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    Text("hello")
                }
            }
            """,
            expandedSource: """
            struct Row: View {
                var body: some View {
                    Text("hello")
                }

                /// The view's `body`, probed, with the VerdictUI root installed.
                ///
                /// Generated by `@Verifiable`. Inert until a `VerdictTreeSink` is
                /// attached, so this is a normal view everywhere else.
                @ViewBuilder
                func verdictProbedBody(into sink: VerdictTreeSink) -> some View {
                    Text("hello").verdictProbe("Row.text.0", role: .text, text: "hello").verdictRoot(into: sink)
                }

                /// The view's `body`, probed, with NO root installed.
                ///
                /// Generated by `@Verifiable`, and this is the member that makes the
                /// two macros COMPOSE. `verdictProbedBody(into:)` installs a root,
                /// and nesting one root inside another is unsupported — the inner
                /// viewport reaches the outer collector and every frame is then
                /// measured against the wrong rectangle. A view rendered INSIDE a
                /// scenario is already under `OracleHost`'s root, so it needs the
                /// probed content and nothing else.
                @ViewBuilder
                var verdictProbedContent: some View {
                    Text("hello").verdictProbe("Row.text.0", role: .text, text: "hello")
                }
            }

            extension Row: VerifiableView {
            }
            """,
            macros: macros
        )
    }

    func testTheIdIsDerivedFromTheTypeNameAndTheElementsPosition() {
        // The id is the macro's contract with every other layer: `TreeDiff`
        // matches on it, `DuplicateProbeIDRule` reports on it, and a baseline
        // recorded in Wave 5 keys on it. Two elements of the same role must
        // therefore get distinct, ORDER-STABLE ids — a single counter shared
        // across roles would renumber every element below an inserted one.
        //
        // The expected indentation below looks wrong and is CORRECT as pinned:
        // the expression is lifted out of `body` and each statement carries the
        // leading trivia it had THERE, so interior lines keep their original
        // depth. That trivia is preserved deliberately — it is the only thing
        // separating a closure's `in` from its first statement, and dropping it
        // produced `{ row inText(…)`, which does not compile (see
        // `testElementsInsideAForEachAreProbedAndTheClosureSurvives`).
        // `SwiftBasicFormat` was tried and measured
        // — it supplies trivia only where trivia is absent, so it cannot
        // re-indent lifted code, and stripping first makes it emit flat output.
        // See the note in `VerifiableMacro.expansion`. Do not "fix" this
        // snapshot to look tidy; change the macro or leave it.
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    VStack {
                        Text("first")
                        Image("icon")
                        Text("second")
                    }
                }
            }
            """,
            expandedSource: """
            struct Row: View {
                var body: some View {
                    VStack {
                        Text("first")
                        Image("icon")
                        Text("second")
