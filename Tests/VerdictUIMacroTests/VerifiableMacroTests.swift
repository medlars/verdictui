    func testANestedCustomViewIsDeferredToTheCompilerWhileItsSiblingsAreProbed() {
        // The plan's "nested custom views" shape. `MyRow()` still gets NO probe
        // of its own — a macro runs on syntax and cannot know a custom type's
        // role, and a wrong role is worse than an absent one because rules act
        // on it. What changed in Task 6 is what happens INSTEAD of nothing.
        //
        // The walk wraps it in `verdictProbing(_:)`, whose two overloads resolve
        // at COMPILE time: the constrained one renders the view's probed content
        // when the type conforms to `VerifiableView` (which `@Verifiable` adds),
        // the passthrough renders it unchanged otherwise. So "nested
        // `@Verifiable` types compose" stopped being a doc-comment promise and
        // became a mechanism — before this, `verdictProbedBody` was generated
        // and NOTHING ever called it, so the two macros over a custom view
        // produced an empty tree and a `vacuous-verdict`.
        //
        // The sibling `Text` is in the same body deliberately: an expansion that
        // probed NOTHING would also satisfy "MyRow carries no probe", so the
        // control is what makes this test able to fail for its own reason.
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    VStack {
                        MyRow()
                        Text("after")
                    }
                }
            }
            """,
            expandedSource: """
            struct Row: View {
                var body: some View {
                    VStack {
                        MyRow()
                        Text("after")
                    }
                }

                /// The view's `body`, probed, with the VerdictUI root installed.
                ///
                /// Generated by `@Verifiable`. Inert until a `VerdictTreeSink` is
                /// attached, so this is a normal view everywhere else.
                @ViewBuilder
                func verdictProbedBody(into sink: VerdictTreeSink) -> some View {
                    VStack {
                                verdictProbing(MyRow())
                                Text("after").verdictProbe("Row.text.0", role: .text, text: "after")
                            } .verdictRoot(into: sink)
                }

                /// The view's `body`, probed, with NO root installed.
                ///
                /// Generated by `@Verifiable`, and this is the member that makes the
                /// two macros COMPOSE. `verdictProbedBody(into:)` installs a root,
                /// and nesting one root inside another is unsupported — the inner
                /// viewport reaches the outer collector and every frame is then
                /// measured against the wrong rectangle. A view rendered INSIDE a
                /// scenario is already under `OracleHost`'s root, so it needs the
                /// probed content and nothing else.
