                var verdictProbedContent: some View {
                    VStack {
                                verdictProbing(MyRow())
                                Text("after").verdictProbe("Row.text.0", role: .text, text: "after")
                            }
                }
            }

            extension Row: VerifiableView {
            }
            """,
            macros: macros
        )
    }

