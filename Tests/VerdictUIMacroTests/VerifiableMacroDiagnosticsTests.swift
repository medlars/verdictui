    func testTwoElementsSharingAnExplicitIdIsAnError() {
        // An id is what every other layer matches on: `TreeDiff` pairs nodes by
        // it, `DuplicateProbeIDRule` reports on it, and Wave 5's baselines key
        // on it. A collision therefore does not merely look untidy — it merges
        // two elements into one for every consumer downstream.
        //
        // The kernel already catches this at RUNTIME, and that is not a reason
        // to skip it here: a runtime rule needs the view rendered in a scenario
        // somebody remembered to write, while the compiler sees every
        // `@Verifiable` view in the module on every build. Reported as an
        // ERROR rather than a warning because there is no reading under which
        // two elements sharing an id is what the author meant.
        //
        // The diagnostic lands on the SECOND occurrence: the first is where the
        // id was legitimately introduced, and pointing at it would send the
        // reader to the wrong line.
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    VStack {
                        Text("a").verdictProbe("same-id", role: .text)
                        Text("b").verdictProbe("same-id", role: .text)
                    }
                }
            }
            """,
            expandedSource: """
            struct Row: View {
                var body: some View {
                    VStack {
                        Text("a").verdictProbe("same-id", role: .text)
                        Text("b").verdictProbe("same-id", role: .text)
                    }
                }

                /// The view's `body`, probed, with the VerdictUI root installed.
                ///
                /// Generated by `@Verifiable`. Inert until a `VerdictTreeSink` is
                /// attached, so this is a normal view everywhere else.
                @ViewBuilder
                func verdictProbedBody(into sink: VerdictTreeSink) -> some View {
                    VStack {
                                Text("a").verdictProbe("same-id", role: .text)
                                Text("b").verdictProbe("same-id", role: .text)
                            } .verdictRoot(into: sink)
                }

                /// The view's `body`, probed, with NO root installed.
                ///
                /// Generated by `@Verifiable`, and this is the member that makes the
                /// two macros COMPOSE. `verdictProbedBody(into:)` installs a root,
                /// and nesting one root inside another is unsupported — the inner
                /// viewport reaches the outer collector and every frame is then
                /// measured against the wrong rectangle. A view rendered INSIDE a
                /// scenario is already under `OracleHost`'s root, so it needs the
                /// probed content and nothing else.
                @ViewBuilder
                var verdictProbedContent: some View {
                    VStack {
                                Text("a").verdictProbe("same-id", role: .text)
                                Text("b").verdictProbe("same-id", role: .text)
                            }
                }
            }

            extension Row: VerifiableView {
            }
            """,
            diagnostics: [
                DiagnosticSpec(
                    message: """
                        Two elements in this view both use the probe id 'same-id'. \
                        Ids must be unique within a view: TreeDiff matches nodes by id \
                        and a baseline keys on it, so a collision silently merges the \
                        two elements. Give this one a different id.
                        """,
                    line: 6,
                    column: 13
                )
            ],
            macros: macros
        )
    }

