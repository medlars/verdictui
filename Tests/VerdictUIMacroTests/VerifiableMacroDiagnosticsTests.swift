    func testAMemberNamedBodyThatIsNotAPropertyDoesNotSatisfyTheRequirement() {
        // `func body()` is not the view's `body`. The detector looks at variable
        // bindings only, so this must still be the no-body error — a detector
        // matching any member named "body" would accept it and then generate
        // code that fails to compile inside the expansion, which is the
        // diagnostic quality this macro exists to avoid.
        assertMacroExpansion(
            """
            @Verifiable
            struct Thing {
                func body() -> Int { 0 }
            }
            """,
            expandedSource: """
            struct Thing {
                func body() -> Int { 0 }
            }
            """,
            diagnostics: [
                DiagnosticSpec(
                    message: """
                        '@Verifiable' needs a 'body' to wrap, and this type declares none. \
                        Add the view's 'body', or remove the attribute.
                        """,
                    line: 1,
                    column: 1
                )
            ],
            macros: macros
        )
    }

    // MARK: - The registry

    func testThePluginRegistersEveryMacroThisModuleImplements() {
        // A macro implemented but unregistered fails at the USE site with
        // "external macro implementation type could not be found", which reads
        // like a toolchain fault. Asserting membership here turns that into a
        // test failure in the module that owns the mistake.
        let registered = VerdictUIMacroPlugin().providingMacros.map { String(describing: $0) }
        XCTAssertTrue(
            registered.contains("VerifiableMacro"),
            "VerifiableMacro is implemented but not listed in VerdictUIMacroPlugin: \(registered)"
        )
    }
