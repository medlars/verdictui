/// Compile-time DIAGNOSTICS for `@Verifiable` and `#VerdictScenario` — the
/// half of the macro surface that reports rather than generates.
///
/// Split from `VerifiableMacroTests` (CTS-E1A2E56A / CTS-5C4D85AB) along the
/// seam the file already had: everything above judged what the macro EMITS,
/// everything here judges what it REFUSES, and the two share only the one-line
/// `macros` dictionary each class declares for itself. That last point is what
/// made this split safe where `no.md` #19 refused one — `ProbeLayoutTests`
/// would have had to widen twelve top-level `private` fixtures to `internal`
/// and collide with a sibling file's same-named `HeadlessHost`, while this file
