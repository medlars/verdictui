    func testAnInteractiveElementWithNoLabelIsAWarningCarryingAFixIt() {
        // The plan calls this "an interactive element with no derivable ID".
        // Measured, that is not what happens: `Button(action:) { Image(…) }`
        // DOES get an id (`Row.button.0`). What it has no way to supply is
        // `text:` — the accessible label — because the only literal in it
        // belongs to the nested `Image`. So the real defect is narrower and
        // worth stating precisely: an interactive element the verdict can point
        // at but cannot NAME. `TruncationRule` has nothing to read, no text
        // assertion can reference it, and a human reading the verdict sees an
        // anonymous button among several.
        //
        // A WARNING, not an error: the view is legitimate SwiftUI, it renders,
        // and it is verifiable in every respect except its label. Escalating it
        // would make `@Verifiable` refuse to compile working code, which is how
        // an adoption-focused tool gets removed rather than fixed.
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    Button(action: save) {
                        Image("gear")
                    }
                }
            }
            """,
            expandedSource: """
            struct Row: View {
                var body: some View {
                    Button(action: save) {
                        Image("gear")
                    }
                }

                /// The view's `body`, probed, with the VerdictUI root installed.
                ///
                /// Generated by `@Verifiable`. Inert until a `VerdictTreeSink` is
                /// attached, so this is a normal view everywhere else.
                @ViewBuilder
                func verdictProbedBody(into sink: VerdictTreeSink) -> some View {
                    Button(action: save) {
                                Image("gear").verdictProbe("Row.image.0", role: .image, text: "gear")
                            } .verdictProbe("Row.button.0", role: .button).verdictRoot(into: sink)
                }

                /// The view's `body`, probed, with NO root installed.
                ///
                /// Generated by `@Verifiable`, and this is the member that makes the
                /// two macros COMPOSE. `verdictProbedBody(into:)` installs a root,
                /// and nesting one root inside another is unsupported — the inner
                /// viewport reaches the outer collector and every frame is then
                /// measured against the wrong rectangle. A view rendered INSIDE a
                /// scenario is already under `OracleHost`'s root, so it needs the
                /// probed content and nothing else.
                @ViewBuilder
                var verdictProbedContent: some View {
                    Button(action: save) {
                                Image("gear").verdictProbe("Row.image.0", role: .image, text: "gear")
                            } .verdictProbe("Row.button.0", role: .button)
                }
            }

            extension Row: VerifiableView {
            }
            """,
            diagnostics: [
                DiagnosticSpec(
                    message: """
                        This button has no label the verdict can name it by, so it is \
                        probed as 'Row.button.0' with no text. Add \
                        '.verdictProbe("Row.button.0", role: .button, text: "…")' with the \
                        label a user would read, or give the button a string label.
                        """,
                    line: 4,
                    column: 9,
                    severity: .warning,
                    fixIts: [FixItSpec(message: "Add an explicit probe carrying the button's label")]
                )
            ],
            macros: macros
        )
    }

    func testALabelledButtonIsNotWarnedAbout() {
        // The control for the warning above. `Button("Save")` forwards its
        // literal as `text:`, so the verdict can name it and there is nothing
        // to report — and without this, "warns about an unlabelled button" is
        // satisfied by an implementation that warns about every button.
        assertMacroExpansion(
            """
            @Verifiable
            struct Row: View {
                var body: some View {
                    Button("Save") { save() }
                }
            }
            """,
            expandedSource: """
